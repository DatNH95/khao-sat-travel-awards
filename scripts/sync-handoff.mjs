import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'hand-off/css');
await mkdir(output, { recursive: true });
const tokens = (await readFile(path.join(root, 'src/styles/tokens.css'), 'utf8')).replace(/\r\n?/g, '\n');
const fontTokens = tokens.match(/^[\t ]*--font-[^\n]+/gm) ?? [];
await writeFile(path.join(output, 'tokens.css'), tokens.replace('@theme static', ':root').replace(/^[\t ]*--color-\*: initial;\n/m, '').replace(/^[\t ]*--font-[^\n]+\n/gm, '').trimEnd() + '\n');
const fontRules = [];
const iconRules = [];
for (const name of ['theme.css', 'mobile_theme.css']) {
  let css = (await readFile(path.join(root, 'public/css', name), 'utf8')).replace(/\r\n?/g, '\n');
  if (/@layer\b|@font-face\b/.test(css)) throw new Error('Review CSS layer/font-face before exporting: ' + name);
  if (name === 'theme.css') {
    css = css.replace(/^(\.[\w:-]+)\s*\{[^\n]*\}\s*$/gm, rule => {
      if (/^\.(?:ui-icon(?:::before)?|home-footer-icon(?:--[\w-]+)?)\s*\{/.test(rule)) { iconRules.push(rule.trim()); return ''; }
      return rule;
    });
    css = css.replace(/^([^{}\n]+)\{([^{}\n]*)\}/gm, (rule, selector, declarations) => {
      const family = declarations.match(/font-family:\s*[^;]+;/g);
      if (!family) return rule;
      fontRules.push(`${selector.trim()} { ${family.join(' ')} }`);
      return `${selector}{${declarations.replace(/font-family:\s*[^;]+;/g, '')}}`;
    });
  }
  await writeFile(path.join(output, name), css.replace(/url\('\/assets\//g, "url('../../public/assets/"));
}
await writeFile(path.join(output, 'font.css'), `/* Exported font configuration; project uses system fonts. */\n:root {\n${fontTokens.join('\n')}\n}\n${fontRules.join('\n')}\n`);
await writeFile(path.join(output, 'icons.css'), iconRules.join('\n').replace(/url\('\/assets\//g, "url('../../public/assets/") + '\n');
await writeFile(path.join(output, 'styles.css'), "/* Generated by pnpm handoff:sync. */\n@import './tokens.css';\n@import './font.css';\n@import './icons.css';\n@import './theme.css';\n@import './mobile_theme.css';\n");
console.log('Synced shared tokens, theme.css and mobile_theme.css into hand-off/css.');

// Use the reviewed production render as the HTML source, then remove all runtime.
// Build first so the handoff always reflects the current implementation.
for (const [route, filename] of [['index', 'index.html'], ['design-system', 'design-system.html']]) {
  let html = await readFile(path.join(root, '.next/server/app', `${route}.html`), 'utf8');
  html = html
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '')
    .replace(/<link\b[^>]*>/gi, '')
    .replace(/<div hidden="">(?:<!--[\s\S]*?-->)*<\/div>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/href="\/design-system"/g, 'href="design-system.html"')
    .replace(/href="\/"/g, 'href="index.html"')
    .replace('</head>', '<link rel="stylesheet" href="css/styles.css"></head>');
  html = html.replace(/src="\/assets\//g, 'src="../public/assets/');
  // The handoff is HTML/CSS only; interactions remain in the app preview.
  html = html.replace(/<button\b([^>]*)>/gi, (tag, attributes) => /\bdisabled(?:\s|=|$)/i.test(attributes) ? tag : `<button${attributes} disabled="">`);
  html = html.replace(/<(input|select|textarea)\b([^>]*)>/gi, (tag, name, attributes) => /\bdisabled(?:\s|=|$)/i.test(attributes) ? tag : `<${name}${attributes.replace(/\/$/, '')} disabled="">`);
  if (route === 'design-system') {
    html = html.replace('Hai bước minh họa để kiểm tra cấu trúc và điều hướng. Số bước khảo sát chính thức chưa được xác định.', 'Hai bước minh họa cấu trúc. Bản HTML/CSS chỉ hiển thị trạng thái tĩnh; xem điều hướng trong app. Số bước chính thức chưa xác định.');
  }
  if (route === 'index') {
    html = html.replace('Đang tải lịch sử…', 'Lịch sử chỉ hiển thị trong ứng dụng trên trình duyệt đã lưu khảo sát. Bản HTML/CSS không tải dữ liệu.');
  }
  if (/<script\b|\/_next\/|(?:href|src)="\/(?!\/)/i.test(html)) throw new Error(`Runtime or absolute local URL remains in ${filename}`);
  await writeFile(path.join(root, 'hand-off', filename), html.replace(/></g, '>\n<'));
}
console.log('Exported both pages as static HTML without framework runtime.');
execFileSync(process.execPath, [path.join(root, 'scripts/export-handoff-states.cjs')], { stdio: 'inherit' });
